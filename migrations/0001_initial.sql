-- X Content AI Agent Database Schema
-- Version: 1.0.0
-- Created: 2024-11-25

-- Research topics discovered by the researcher agent
CREATE TABLE research_topics (
  id TEXT PRIMARY KEY,
  topic TEXT NOT NULL,
  category TEXT NOT NULL,
  summary TEXT NOT NULL,
  verified_facts TEXT NOT NULL, -- JSON array
  source_urls TEXT NOT NULL, -- JSON array
  source_publication_dates TEXT NOT NULL, -- JSON array
  audience_relevance REAL NOT NULL,
  novelty_score REAL NOT NULL,
  freshness_score REAL NOT NULL,
  content_opportunity_score REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'discovered', -- discovered, analyzed, used, archived
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  metadata TEXT -- JSON for additional data
);

-- Viral content frameworks from analysis
CREATE TABLE viral_frameworks (
  id TEXT PRIMARY KEY,
  source_post_url TEXT,
  source_post_text TEXT,
  source_post_metrics TEXT, -- JSON
  context_analysis TEXT, -- JSON: cultural moment, audience, network, etc.
  mechanisms_identified TEXT NOT NULL, -- JSON array of mechanisms
  frameworks_extracted TEXT NOT NULL, -- JSON array of F1-F8 frameworks
  transferable_principle TEXT NOT NULL,
  competing_explanations TEXT, -- JSON array
  original_applications TEXT, -- JSON array of generated applications
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Content drafts generated by copywriter, scored by editor
CREATE TABLE content_drafts (
  id TEXT PRIMARY KEY,
  draft_id TEXT NOT NULL UNIQUE,
  topic_id TEXT REFERENCES research_topics(id),
  topic TEXT NOT NULL,
  category TEXT NOT NULL,
  content_format TEXT NOT NULL,
  target_audience TEXT NOT NULL,
  hook_type TEXT NOT NULL,
  primary_hook TEXT NOT NULL,
  alternative_hooks TEXT NOT NULL, -- JSON array
  recommended_post TEXT NOT NULL,
  alternative_posts TEXT NOT NULL, -- JSON array
  character_count INTEGER NOT NULL,
  content_framework TEXT NOT NULL,
  core_insight TEXT NOT NULL,
  originality_score REAL NOT NULL,
  editorial_score REAL NOT NULL,
  engagement_potential TEXT NOT NULL, -- low, medium, high, very_high
  fact_check_status TEXT NOT NULL, -- passed, failed, needs_review
  verified_claims TEXT NOT NULL, -- JSON array
  source_urls TEXT NOT NULL, -- JSON array
  source_publication_dates TEXT NOT NULL, -- JSON array
  visual_content_suggestion TEXT,
  reason_for_selection TEXT NOT NULL,
  platform_compliance_status TEXT NOT NULL, -- compliant, needs_review, non_compliant
  requires_manual_publication INTEGER NOT NULL DEFAULT 1, -- boolean
  status TEXT NOT NULL DEFAULT 'pending_approval', -- pending_approval, approved, rejected, published, archived
  generation_mode TEXT NOT NULL, -- automatic, topic, url, viral_framework, evergreen
  input_parameters TEXT, -- JSON
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  approved_at INTEGER,
  published_at INTEGER
);

-- Human feedback on drafts for learning
CREATE TABLE feedback (
  id TEXT PRIMARY KEY,
  draft_id TEXT NOT NULL REFERENCES content_drafts(draft_id),
  feedback_type TEXT NOT NULL, -- approval, rejection, edit, rewrite, rating
  rating INTEGER, -- 1-10
  liked_elements TEXT, -- JSON array
  disliked_elements TEXT, -- JSON array
  suggested_changes TEXT,
  editor_notes TEXT,
  applied_to_future_generation INTEGER NOT NULL DEFAULT 0, -- boolean
  created_at INTEGER NOT NULL
);

-- Persistent brand memory and learned patterns
CREATE TABLE brand_memory (
  id TEXT PRIMARY KEY,
  memory_type TEXT NOT NULL, -- successful_framework, audience_preference, writing_pattern, editorial_feedback, rejected_pattern, performance_insight
  content TEXT NOT NULL,
  source TEXT NOT NULL, -- feedback, analysis, manual, performance_data
  confidence REAL NOT NULL DEFAULT 0.5,
  usage_count INTEGER NOT NULL DEFAULT 0,
  last_used_at INTEGER,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  metadata TEXT -- JSON
);

-- Historical performance data for posts
CREATE TABLE performance_data (
  id TEXT PRIMARY KEY,
  draft_id TEXT NOT NULL REFERENCES content_drafts(draft_id),
  post_text TEXT NOT NULL,
  published_at INTEGER NOT NULL,
  platform_post_id TEXT, -- X post ID
  impressions INTEGER,
  likes INTEGER,
  replies INTEGER,
  reposts INTEGER,
  quotes INTEGER,
  bookmarks INTEGER,
  profile_visits INTEGER,
  link_clicks INTEGER,
  follower_growth INTEGER,
  engagement_rate REAL,
  qualified_inquiries INTEGER,
  content_category TEXT,
  hook_type TEXT,
  publishing_time_hour INTEGER, -- 0-23
  publishing_time_day INTEGER, -- 0-6 (Sunday=0)
  approval_rate REAL,
  rejection_reasons TEXT, -- JSON array
  human_editing_preferences TEXT, -- JSON
  snapshot_at INTEGER NOT NULL, -- when metrics were captured
  created_at INTEGER NOT NULL
);

-- Workflow execution state for durability
CREATE TABLE workflow_executions (
  id TEXT PRIMARY KEY,
  workflow_name TEXT NOT NULL,
  status TEXT NOT NULL, -- running, completed, failed, paused
  current_step TEXT,
  input_parameters TEXT, -- JSON
  step_outputs TEXT, -- JSON
  error_message TEXT,
  retry_count INTEGER NOT NULL DEFAULT 0,
  started_at INTEGER NOT NULL,
  completed_at INTEGER,
  updated_at INTEGER NOT NULL
);

-- Indexes for common queries
CREATE INDEX idx_research_topics_status ON research_topics(status);
CREATE INDEX idx_research_topics_category ON research_topics(category);
CREATE INDEX idx_research_topics_created_at ON research_topics(created_at);
CREATE INDEX idx_research_topics_opportunity_score ON research_topics(content_opportunity_score);

CREATE INDEX idx_content_drafts_status ON content_drafts(status);
CREATE INDEX idx_content_drafts_topic_id ON content_drafts(topic_id);
CREATE INDEX idx_content_drafts_created_at ON content_drafts(created_at);
CREATE INDEX idx_content_drafts_editorial_score ON content_drafts(editorial_score);

CREATE INDEX idx_feedback_draft_id ON feedback(draft_id);
CREATE INDEX idx_feedback_created_at ON feedback(created_at);

CREATE INDEX idx_brand_memory_type ON brand_memory(memory_type);
CREATE INDEX idx_brand_memory_confidence ON brand_memory(confidence);

CREATE INDEX idx_performance_data_draft_id ON performance_data(draft_id);
CREATE INDEX idx_performance_data_published_at ON performance_data(published_at);
CREATE INDEX idx_performance_data_category ON performance_data(content_category);

CREATE INDEX idx_workflow_executions_status ON workflow_executions(status);
CREATE INDEX idx_workflow_executions_started_at ON workflow_executions(started_at);